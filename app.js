function yen(n){
  const sign = n > 0 ? "+" : "";
  return sign + n.toLocaleString("ja-JP") + " 円";
}

function yenNoUnit(n){
  const sign = n > 0 ? "+" : "";
  return sign + n.toLocaleString("ja-JP");
}

function amountMarkup(n){
  return `<span class="amount-value">${yenNoUnit(n)}</span><span class="yen">円</span>`;
}

function runningMarkup(balance){
  if (balance == null) {
    return `<span class="running-label">残高</span><span class="running-value">--</span><span class="yen">円</span>`;
  }
  return `<span class="running-label">残高</span><span class="running-value">${balance.toLocaleString("ja-JP")}</span><span class="yen">円</span>`;
}

