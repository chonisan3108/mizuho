function updateMemoButtons(){
  const value = memoInput.value;
  saveMemo.disabled =
    currentTransactionIndex === null ||
    value.trim().length === 0 ||
    value === openedMemoValue;

  deleteMemo.disabled =
    currentTransactionIndex === null ||
    openedMemoValue.length === 0;
}

function openTransaction(index){
  const t = currentDetailTransactions[index];
  currentTransactionIndex = index;

  document.getElementById("transactionType").textContent = t.amount >= 0 ? "入金" : "支出";

  const amountEl = document.getElementById("transactionAmount");
  amountEl.textContent = (t.amount > 0 ? "+" : "") + t.amount.toLocaleString("ja-JP");
  amountEl.style.color = t.amount > 0 ? "#66d89d" : "#ffffff";

  document.getElementById("transactionBalance").textContent =
    t.balance == null ? "-- 円" : t.balance.toLocaleString("ja-JP") + " 円";
  document.getElementById("transactionName").textContent = t.name;
  document.getElementById("transactionDate").textContent = t.date;

  const key = transactionMemoKey(t, index);
  openedMemoValue = transactionMemos[key] || "";
  memoInput.value = openedMemoValue;
  updateMemoButtons();

  showView("transaction");
}

