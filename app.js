const reportKeysFromStatements = Object.keys(detailTransactionsByMonth).sort();

function reportWeekday(year, month, day){
  const names = ["日","月","火","水","木","金","土"];
  return names[new Date(year, month - 1, day).getDay()];
}

function reportDateLabel(year, month, day){
  return `${year}年${month}月${day}日(${reportWeekday(year, month, day)})`;
}

function reportPreviousKey(key){
  const [year, month] = key.split("-").map(Number);
  const d = new Date(year, month - 2, 1);
  return `${d.getFullYear()}-${String(d.getMonth() + 1).padStart(2,"0")}`;
}

function reportRowFromTransaction(t){
  return [
    t.name,
    `${t.amount > 0 ? "+" : "-"}${Math.abs(t.amount).toLocaleString("ja-JP")} 円`,
    "鎌倉支店",
    "普通 3031681",
    t.date
  ];
}

function buildReportData(){
  const summaries = {};

  reportKeysFromStatements.forEach(key=>{
    const txs = detailTransactionsByMonth[key] || [];
    const income = txs.reduce((sum,t)=>sum + (t.amount > 0 ? t.amount : 0), 0);
    const expense = txs.reduce((sum,t)=>sum + (t.amount < 0 ? t.amount : 0), 0);
    summaries[key] = { income, expense, net: income + expense };
  });

  return Object.fromEntries(reportKeysFromStatements.map(key=>{
    const [year, month] = key.split("-").map(Number);
    const txs = detailTransactionsByMonth[key] || [];
    const { income, expense, net } = summaries[key];
    const isCurrent = key === "2026-08";
    const fullDays = new Date(year, month, 0).getDate();
    const elapsedDays = isCurrent ? 29 : fullDays;
    const daily = Math.round(Math.abs(expense) / Math.max(1, elapsedDays));

    const expenseRows = txs
      .filter(t=>t.amount < 0)
      .sort((a,b)=>a.amount-b.amount)
      .slice(0,3)
      .map(reportRowFromTransaction);

    const incomeRows = txs
      .filter(t=>t.amount > 0)
      .sort((a,b)=>b.amount-a.amount)
      .slice(0,3)
      .map(reportRowFromTransaction);

    let text = `1日平均で言うと約 <span class="red-text">${daily.toLocaleString("ja-JP")}</span> 円使っています。`;
    const previous = summaries[reportPreviousKey(key)];

    if (!isCurrent && previous) {
      const expenseDiff = Math.abs(expense) - Math.abs(previous.expense);
      const incomeDiff = income - previous.income;
      const expenseDirection = expenseDiff > 0 ? "多く" : expenseDiff < 0 ? "少なく" : "同じに";
      const incomeDirection = incomeDiff > 0 ? "多く" : incomeDiff < 0 ? "少なく" : "同じに";
      text = `先月と比べて支出が <span class="red-text">${Math.abs(expenseDiff).toLocaleString("ja-JP")}</span> 円${expenseDirection}、収入は <span class="blue-text">${Math.abs(incomeDiff).toLocaleString("ja-JP")}</span> 円${incomeDirection}なっています。1日平均で言うと約 <span class="red-text">${daily.toLocaleString("ja-JP")}</span> 円使っています。`;
    }

    return [key, {
      title:`${year}年${month}月`,
      income,
      expense,
      net,
      evalTitle:isCurrent ? "今月の評価" : `${month}月の評価`,
      evalDate:isCurrent
        ? `${reportDateLabel(year,month,1)} - ${reportDateLabel(year,month,29)}`
        : `${reportDateLabel(year,month,1)} - ${reportDateLabel(year,month,fullDays)}`,
      badge:isCurrent ? "残り2日" : (net >= 0 ? "☺ 黒字" : "赤字"),
      badgeType:!isCurrent && net >= 0 ? "profit" : "",
      text,
      expenseRows,
      incomeRows
    }];
  }));
}

const reportData = buildReportData();

const graphKeys = Object.keys(reportData);
let selectedReportKey = "2026-08";

const chartScroller = document.getElementById("chartScroller");
const reportChart = document.getElementById("reportChart");

const SVG_NS = "http://www.w3.org/2000/svg";
const CHART = {
  leftPad: 55,
  cell: 78,
  top: 28,
  baseline: 142,
  bottom: 256,
  labelY: 281,
  underlineY: 286,
  height: 290
};

function svgEl(name, attrs={}){
  const el = document.createElementNS(SVG_NS, name);
  Object.entries(attrs).forEach(([k,v])=>el.setAttribute(k, String(v)));
  return el;
}

function xForIndex(index){
  return CHART.leftPad + index * CHART.cell + CHART.cell / 2;
}

function renderReportChart(){
  const previousScroll = chartScroller.scrollLeft;
  const width = CHART.leftPad + graphKeys.length * CHART.cell + 24;

  reportChart.setAttribute("viewBox", `0 0 ${width} ${CHART.height}`);
  reportChart.setAttribute("width", width);
  reportChart.setAttribute("height", CHART.height);
  reportChart.style.width = `${width}px`;
  reportChart.innerHTML = "";

  // 選択中の月を先に描いて、棒グラフの背面へ
  const selectedIndex = graphKeys.indexOf(selectedReportKey);
  if (selectedIndex >= 0) {
    const sx = xForIndex(selectedIndex);
    reportChart.appendChild(svgEl("rect", {
      x:sx - CHART.cell/2,
      y:CHART.top,
      width:CHART.cell,
      height:CHART.underlineY - CHART.top,
      class:"month-bg"
    }));
    reportChart.appendChild(svgEl("rect", {
      x:sx - CHART.cell/2,
      y:CHART.underlineY,
      width:CHART.cell,
      height:4,
      class:"month-underline"
    }));
  }

  // 横線
  reportChart.appendChild(svgEl("line", {
    x1:0, y1:CHART.top, x2:width, y2:CHART.top, class:"grid"
  }));
  reportChart.appendChild(svgEl("line", {
    x1:0, y1:CHART.baseline, x2:width, y2:CHART.baseline, class:"axis"
  }));
  reportChart.appendChild(svgEl("line", {
    x1:0, y1:CHART.bottom, x2:width, y2:CHART.bottom, class:"grid"
  }));

  const points = [];

  graphKeys.forEach((key,index)=>{
    const d = reportData[key];
    const x = xForIndex(index);

    reportChart.appendChild(svgEl("line", {
      x1:x, y1:CHART.top, x2:x, y2:CHART.bottom, class:"vgrid"
    }));

    const incomeHeight = Math.max(8, Math.min(105, Math.abs(d.income) / 400000 * 114));
    const expenseHeight = Math.max(8, Math.min(105, Math.abs(d.expense) / 400000 * 114));

    reportChart.appendChild(svgEl("rect", {
      x:x-4,
      y:CHART.baseline-incomeHeight,
      width:8,
      height:incomeHeight,
      rx:4,
      class:"income-bar"
    }));

    reportChart.appendChild(svgEl("rect", {
      x:x-4,
      y:CHART.baseline,
      width:8,
      height:expenseHeight,
      rx:4,
      class:"expense-bar"
    }));

    const netY = CHART.baseline - Math.max(-28, Math.min(28, d.net / 400000 * 65));
    points.push(`${x},${netY}`);

    const [,monthString] = key.split("-");
    const label = svgEl("text", {
      x,
      y:CHART.labelY,
      class:"month-label"
    });
    label.textContent = `${Number(monthString)}月`;
    reportChart.appendChild(label);
  });

  reportChart.appendChild(svgEl("polyline", {
    points: points.join(" "),
    class:"net-line"
  }));

  // どこをタップしても月選択できる透明ヒット領域
  graphKeys.forEach((key,index)=>{
    const x = xForIndex(index);
    const hit = svgEl("rect", {
      x:x-CHART.cell/2,
      y:0,
      width:CHART.cell,
      height:CHART.height,
      class:"month-hit",
      tabindex:"0",
      role:"button",
      "aria-label":`${reportData[key].title}を表示`
    });

    hit.addEventListener("click",()=>selectReportMonth(key));

    hit.addEventListener("keydown",(event)=>{
      if (event.key === "Enter" || event.key === " ") {
        event.preventDefault();
        selectReportMonth(key);
      }
    });

    reportChart.appendChild(hit);
  });

  // 再描画で横スクロール位置を失わない
  chartScroller.scrollLeft = previousScroll;
}

function ensureSelectedMonthVisible(smooth=true){
  const index = graphKeys.indexOf(selectedReportKey);
  if (index < 0) return;

  const centerX = xForIndex(index);
  const target = centerX - chartScroller.clientWidth / 2;
  const maxScroll = Math.max(0, reportChart.scrollWidth - chartScroller.clientWidth);
  const left = Math.max(0, Math.min(maxScroll, target));

  chartScroller.scrollTo({
    left,
    behavior: smooth ? "smooth" : "auto"
  });
}

function renderRows(containerId, rows){
  const el = document.getElementById(containerId);
  el.innerHTML = "";

  rows.forEach(r=>{
    el.insertAdjacentHTML("beforeend", `
      <div class="report-row">
        <div class="report-row-left">
          <div class="report-row-title">${r[0]}</div>
          <div class="report-row-sub">${r[2]}</div>
          <div class="report-row-sub">${r[3]}</div>
        </div>
        <div class="report-row-right">
          <div class="report-row-amount">${r[1]}</div>
          <div class="report-row-date">${r[4]}</div>
        </div>
      </div>`);
  });
}

function selectReportMonth(key){
  if (!reportData[key]) return;

  selectedReportKey = key;
  const d = reportData[key];

  document.getElementById("reportMonthTitle").textContent = d.title;
  document.getElementById("reportIncome").innerHTML =
    `${yenNoUnit(d.income)}<small>円</small>`;
  document.getElementById("reportExpense").innerHTML =
    `${yenNoUnit(d.expense)}<small>円</small>`;
  document.getElementById("reportNet").innerHTML =
    `${yenNoUnit(d.net)}<small>円</small>`;
  document.getElementById("reportNet").className = d.net >= 0 ? "green" : "red";

  document.getElementById("evaluationTitle").textContent = d.evalTitle;
  document.getElementById("evaluationDate").textContent = d.evalDate;

  const badge = document.getElementById("evaluationBadge");
  badge.textContent = d.badge;
  badge.className = "evaluation-badge" + (d.badgeType === "profit" ? " profit" : "");

  document.getElementById("evaluationText").innerHTML = d.text;

  renderRows("highExpenseList", d.expenseRows);
  renderRows("highIncomeList", d.incomeRows);
  document.getElementById("highIncomeSection").style.display =
    d.incomeRows.length ? "block" : "none";

  renderReportChart();
}

